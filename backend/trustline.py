"""
Litmus TrustLine — Outbound Call Authentication for TVS Credit
================================================================

THE INVERSION
-------------
An OTP makes the CUSTOMER prove identity to the INSTITUTION.
Every voice scam in India exploits exactly that direction:
    "Sir, aapka OTP bataiye."

TrustLine reverses the arrow. The INSTITUTION proves identity to the
CUSTOMER. The code only ever travels outward — TVS Credit issues it,
TVS Credit speaks it, the customer verifies it.

That inversion changes the customer-education message from a rule people
routinely break under pressure:
    "Never share your OTP"
into a rule that is safe even when broken:
    "Always make the caller tell you the TrustLine code."

Leaking a TrustLine phrase teaches an attacker nothing. It is session-bound,
single-use, time-limited and HMAC-keyed to a server secret. A scammer who
overhears one cannot mint another, cannot replay it into a different session,
and cannot use it against a different customer.

WHY THIS SITS ABOVE THE 1600-SERIES MANDATE
-------------------------------------------
TRAI has mandated the 1600-number series for BFSI service and transactional
calls (NBFCs phased in Feb-Mar 2026). That mandate authenticates the NUMBER.
It does not authenticate the HUMAN, it does not cover WhatsApp/OTT calls,
and it does not survive CLI spoofing.

Worse: by training 2.44 crore TVS Credit customers that "1600 == genuinely
TVS", the mandate manufactures a trust signal that is now worth stealing.
TrustLine is a shared-secret challenge rather than an identity display, so
it survives caller-ID spoofing by construction.

WHY THIS DOES NOT DEPEND ON VOICE DETECTION ACCURACY
----------------------------------------------------
Litmus's own measured results: the voice ensemble catches ~35% of 2019-era
TTS and 0% of modern neural TTS. TrustLine was designed around that ceiling,
not in spite of it. A challenge-response code is a possession/knowledge
factor. A perfect voice clone still cannot produce it.

SECURITY PROPERTIES IMPLEMENTED HERE
------------------------------------
  1. Unforgeable      — HMAC-SHA256 under a server-held secret
  2. Session-bound    — phrase binds customer + agent + session + purpose
  3. Time-limited     — TTL, default 10 minutes
  4. Single-use       — verification burns the session
  5. Constant-time    — hmac.compare_digest, no timing oracle
  6. Out-of-band      — delivered on a channel the caller does not control
  7. Fail-loud        — a verification with NO active session is the single
                        strongest scam signal available, and is escalated

FRAUD INTELLIGENCE (the part no KYC vendor can offer)
-----------------------------------------------------
Every failed verification is a scammer revealing themselves in real time.
TrustLine records the claimed purpose, the caller number, and the timing,
and clusters them into live campaign alerts. TVS Credit gets a fraud feed
generated by the attackers themselves.
"""

